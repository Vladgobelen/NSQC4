-- ============================================================================
-- Настройки отображения
-- ============================================================================
local INDENT_BY_LEVEL = { [1] = 12, [2] = 28, [3] = 44, ["note"] = 28, ["warning"] = 28 }

local FONT_BY_LEVEL = {
    [1]         = { font = "GameFontNormalLarge", r = 1.00, g = 0.82, b = 0.00 },
    [2]         = { font = "GameFontNormal",      r = 1.00, g = 1.00, b = 1.00 },
    [3]         = { font = "GameFontNormalSmall", r = 0.80, g = 0.80, b = 0.80 },
    ["note"]    = { font = "GameFontNormalSmall", r = 0.70, g = 0.70, b = 0.70 },
    ["warning"] = { font = "GameFontNormal",      r = 1.00, g = 0.15, b = 0.15 },
}

local LINE_SPACING = 6
local SECTION_SPACING = 8
local HEADER_HEIGHT = 40
local PADDING = 20

-- ============================================================================
-- Окно устава
-- ============================================================================
local charterFrame
local rows = {}

local function CreateCharterFrame()
    if charterFrame then
        return charterFrame
    end

    local f = CreateFrame("Frame", "NSQC4CharterFrame", UIParent)
    charterFrame = f
    f:SetSize(620, 560)
    f:SetPoint("CENTER")
    f:SetFrameStrata("DIALOG")
    f:SetToplevel(true)
    f:SetMovable(true)
    f:EnableMouse(true)
    f:SetClampedToScreen(true)
    f:RegisterForDrag("LeftButton")
    f:SetScript("OnDragStart", function(self) self:StartMoving() end)
    f:SetScript("OnDragStop", function(self) self:StopMovingOrSizing() end)

    f:SetBackdrop({
        bgFile   = "Interface\\Buttons\\WHITE8x8",
        edgeFile = "Interface\\DialogFrame\\UI-DialogBox-Border",
        tile = false,
        edgeSize = 32,
        insets = { left = 8, right = 8, top = 8, bottom = 8 },
    })
    f:SetBackdropColor(0, 0, 0, 1)

    -- Иконка-свиток
    local icon = f:CreateTexture(nil, "ARTWORK")
    icon:SetSize(28, 28)
    icon:SetPoint("TOPLEFT", 12, -10)
    icon:SetTexture("Interface\\Icons\\INV_Scroll_03")

    -- Заголовок
    local title = f:CreateFontString(nil, "OVERLAY", "GameFontNormalLarge")
    title:SetPoint("TOP", 0, -14)
    title:SetText("Устав гильдии Ночная стража")
    title:SetTextColor(1, 0.82, 0)

    -- Кнопка закрытия
    local close = CreateFrame("Button", nil, f, "UIPanelCloseButton")
    close:SetPoint("TOPRIGHT", -6, -6)

    -- Скролл
    local scroll = CreateFrame("ScrollFrame", "NSQC4CharterScroll", f, "UIPanelScrollFrameTemplate")
    scroll:SetPoint("TOPLEFT", PADDING, -HEADER_HEIGHT)
    scroll:SetPoint("BOTTOMRIGHT", -PADDING - 20, PADDING)
    f.scroll = scroll

    local content = CreateFrame("Frame", nil, scroll)
    content:SetSize(560, 100)
    content:SetPoint("TOPLEFT")
    scroll:SetScrollChild(content)
    f.content = content

    -- Лейаут секций
    local y = -4
    local lastLevel = 1

    for i, section in ipairs(SECTIONS) do
        local level = section.level
        local style = FONT_BY_LEVEL[level] or FONT_BY_LEVEL[1]
        local indent = INDENT_BY_LEVEL[level] or 12

        -- Отступ перед новым основным пунктом (кроме первого)
        if level == 1 and i > 1 then
            y = y - SECTION_SPACING
        end

        local fs = content:CreateFontString(nil, "OVERLAY", style.font)
        fs:SetPoint("TOPLEFT", indent, y)
        fs:SetWidth(560 - indent - 10)
        fs:SetJustifyH("LEFT")
        fs:SetJustifyV("TOP")
        fs:SetNonSpaceWrap(true)
        fs:SetSpacing(2)
        fs:SetTextColor(style.r, style.g, style.b, 1)

        -- Для note — курсивного шрифта нет в стандарте, используем префикс
        if level == "note" then
            fs:SetText("   " .. section.text)
        elseif level == 3 then
            -- Для под-подпунктов добавляем точку-маркер
            fs:SetText(section.id .. " " .. section.text)
        else
            fs:SetText(section.id .. ". " .. section.text)
        end

        -- Ждём расчёта высоты — используем OnUpdate через content
        table.insert(rows, {
            fontString = fs,
            section = section,
            y = y,
        })

        -- Приблизительная высота (уточним при первом Layout)
        y = y - 20
    end

    -- Функция перерасчёта (после того, как FontString'и получили высоту)
    local function Layout()
        local curY = -4
        for i, row in ipairs(rows) do
            local level = row.section.level

            if level == 1 and i > 1 then
                curY = curY - SECTION_SPACING
            end

            row.fontString:ClearAllPoints()
            local indent = INDENT_BY_LEVEL[level] or 12
            row.fontString:SetPoint("TOPLEFT", indent, curY)

            local h = row.fontString:GetStringHeight() or 16
            curY = curY - h - LINE_SPACING
        end

        content:SetHeight(math.max(100, -curY + 20))
    end

    f.Layout = Layout
    f:SetScript("OnShow", function()
        Layout()
    end)

    f:Hide()
    return f
end

-- ============================================================================
-- Публичный API
-- ============================================================================
NSQC4.Charter = NSQC4.Charter or {}

function NSQC4.Charter:Show()
    local f = CreateCharterFrame()
    f:Show()
    f:Raise()
    if f.Layout then
        f:Layout()
    end
end

function NSQC4.Charter:Hide()
    if charterFrame then
        charterFrame:Hide()
    end
end

function NSQC4.Charter:Toggle()
    local f = CreateCharterFrame()
    if f:IsShown() then
        f:Hide()
    else
        self:Show()
    end
end

