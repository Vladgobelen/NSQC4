-- ============================================================================
-- NSQC4 / Core / SlashCommands
-- Список слэш-команд для панели быстрого доступа (ЛКМ по иконке аддона).
-- ============================================================================

NSQC4 = NSQC4 or {}
NSQC4.SlashCommands = {
    { label = "T", cmd = "/nstimer",   desc = "Показать/скрыть кнопку таймера." },
    { label = "?", cmd = "/nsqc4help", desc = "Показать все слэш-команды аддона." },
}

-- ============================================================================
-- Слэш-команда помощи
-- ============================================================================
SLASH_NSQC4HELP1 = "/nsqc4help"
SlashCmdList["NSQC4HELP"] = function()
    print("|cff00ff00[NSQC4]|r Слэш-команды:")
    for _, entry in ipairs(NSQC4.SlashCommands) do
        print("  |cffffff00" .. entry.cmd .. "|r — " .. entry.desc)
    end
end