-- ============================================================================
-- NSQC4 / TextQuests / Core / Reply
-- Ответы движка в офицерский чат (логи аддона).
-- Без цветов и без символа "|" — на сервере запрещены.
-- ============================================================================

NSQC4 = NSQC4 or {}
NSQC4.TextQuests = NSQC4.TextQuests or {}

-- ============================================================================
-- Отправить строку в OFFICER.
-- ============================================================================
function NSQC4.TextQuests.Say(text)
    if text == nil then return end
    SendChatMessage(tostring(text), "OFFICER")
end