-- ============================================================================
-- NSQC4 / Quests / df / Terrain / Logic / Grass
-- Логика и свойства типа "Трава" (grass).
--
-- Только поведение: onClick и contextMenu.
-- Базовые характеристики (hardness, texture, textSize, color) —
-- в df/Terrain/Data/Grass.lua.
-- ============================================================================

NSQC4.RegisterModule("quests", function()
    local Terrain = NSQC4.QuestsDfTerrain
    if not Terrain then return end

    -- ========================================================================
    -- РЕГИСТРАЦИЯ СЕБЯ В СИСТЕМЕ
    -- ========================================================================
    Terrain:RegisterType("grass", {
        -- ====================================================================
        -- ЛОГИКА КЛИКА (ЛКМ)
        -- ====================================================================
        onClick = function(index)
            Terrain:SetTerrain(index, "earth")
            print("|cff00ff00[NSQC4]|r Трава вытоптана в клетке " .. index)
        end,

        -- ====================================================================
        -- КОНТЕКСТНОЕ МЕНЮ (ПКМ)
        -- ====================================================================
        contextMenu = {
            { text = "Вытоптать (сделать землей)", func = function(index)
                Terrain:SetTerrain(index, "earth")
            end },
            { text = "Собрать семена", func = function(index)
                print("|cff00ff00[NSQC4]|r Вы собрали семена с клетки " .. index)
            end }
        }
    })
end)