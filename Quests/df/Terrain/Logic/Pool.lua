-- ============================================================================
-- NSQC4 / Quests / df / Terrain / Logic / Pool
-- Логика и свойства типа "Бассейн" (pool).
--
-- Только поведение: onClick и contextMenu.
-- Базовые характеристики (hardness, texture, textSize, color) —
-- в df/Terrain/Data/Pool.lua.
-- ============================================================================

NSQC4.RegisterModule("quests", function()
    local Terrain = NSQC4.QuestsDfTerrain
    if not Terrain then return end

    -- ========================================================================
    -- РЕГИСТРАЦИЯ СЕБЯ В СИСТЕМЕ
    -- ========================================================================
    Terrain:RegisterType("pool", {
        -- ====================================================================
        -- ЛОГИКА КЛИКА (ЛКМ)
        -- ====================================================================
        onClick = function(index)
            print("|cff00ff00[NSQC4]|r Вы попили воды из бассейна в клетке " .. index)
        end,

        -- ====================================================================
        -- КОНТЕКСТНОЕ МЕНЮ (ПКМ)
        -- ====================================================================
        contextMenu = {
            { text = "Выпить воды", func = function(index)
                print("|cff00ff00[NSQC4]|r Вы попили воды из бассейна в клетке " .. index)
            end },
            { text = "Снести бассейн", func = function(index)
                -- Возвращаем землю на место бассейна
                Terrain:SetTerrain(index, "earth")
                print("|cffff8800[NSQC4]|r Бассейн снесен в клетке " .. index)
            end }
        }
    })
end)