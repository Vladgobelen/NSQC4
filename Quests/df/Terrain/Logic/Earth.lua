-- ============================================================================
-- NSQC4 / Quests / df / Terrain / Logic / Earth
-- Логика и свойства типа "Земля" (earth).
--
-- Только поведение: onClick и contextMenu.
-- Базовые характеристики (hardness, texture, textSize, color) —
-- в df/Terrain/Data/Earth.lua.
-- ============================================================================

NSQC4.RegisterModule("quests", function()
    local Terrain = NSQC4.QuestsDfTerrain
    if not Terrain then return end

    -- ========================================================================
    -- РЕГИСТРАЦИЯ СЕБЯ В СИСТЕМЕ
    -- ========================================================================
    Terrain:RegisterType("earth", {
        -- ====================================================================
        -- ЛОГИКА КЛИКА (ЛКМ)
        -- ====================================================================
        onClick = function(index)
            -- Земля — это базовый фон. ЛКМ по ней обычно просто выделяет клетку,
            -- поэтому тут можно оставить пустоту (или лог).
        end,

        -- ====================================================================
        -- КОНТЕКСТНОЕ МЕНЮ (ПКМ)
        -- ====================================================================
        contextMenu = {
            { text = "Постройка бассейна", func = function(index)
                -- Меняем землю на бассейн
                Terrain:SetTerrain(index, "pool")
                print("|cff00ff00[NSQC4]|r Бассейн построен в клетке " .. index)
            end },
            { text = "Вскопать грядки", func = function(index)
                Terrain:SetTerrain(index, "grass")
            end }
        }
    })
end)