-- ============================================================================
-- NSQC4 / Quests / df / Terrain / Logic / Tree
-- Логика и свойства типа "Дерево" (tree).
--
-- Только поведение: onClick и contextMenu.
-- Базовые характеристики (hardness, texture, textSize, color) —
-- в df/Terrain/Data/Tree.lua.
-- ============================================================================

NSQC4.RegisterModule("quests", function()
    local Terrain = NSQC4.QuestsDfTerrain
    if not Terrain then return end

    -- ========================================================================
    -- РЕГИСТРАЦИЯ СЕБЯ В СИСТЕМЕ
    -- ========================================================================
    Terrain:RegisterType("tree", {
        -- ====================================================================
        -- ЛОГИКА КЛИКА (ЛКМ)
        -- ====================================================================
        onClick = function(index)
            -- Срубаем дерево (меняем на землю)
            Terrain:SetTerrain(index, "earth")
            print("|cff00ff00[NSQC4]|r Дерево срублено в клетке " .. index)
        end,

        -- ====================================================================
        -- КОНТЕКСТНОЕ МЕНЮ (ПКМ)
        -- ====================================================================
        contextMenu = {
            { text = "Срубить дерево", func = function(index)
                Terrain:SetTerrain(index, "earth")
                print("|cff00ff00[NSQC4]|r Дерево срублено в клетке " .. index)
            end },
            { text = "Осмотреть", func = function(index)
                print("|cff00ff00[NSQC4]|r Вы осмотрели дерево в клетке " .. index)
            end }
        }
    })
end)