-- ============================================================================
-- NSQC4 / Quests / df / Professions / Swimmer
-- Профессия «Пловец». Позволяет существу пересекать воду (water).
--
-- Профессия — самостоятельная единица. Знает:
--   - к каким объектам применяется (terrain = "water")
--   - каким параметром существа ускоряется (stat = "agility")
--   - как считать клики под конкретный объект (clicks)
--   - что даёт по завершении (work.yields)
--
-- ВАЖНО: вода НЕ добывается работой. Пловец нужен для ПРОХОДИМОСТИ
-- (Path/Move проверяют Resolve:CanSwim(entity) и пускают в воду только
-- существ с этой профессией). Поэтому:
--   - clicks   — заглушка (всегда 1), вода не «копается»
--   - yields   — nil, ничего не даёт по завершении
--   - hardness — 0 (см. df/Terrain/Data/Water.lua), работы по hardness нет
--
-- Отдельная логика работы на воде (если появится) — в
-- df/Actions/Terrain/Water/*, а не здесь. Профессия отвечает только за
-- право находиться в воде и за формулу кликов (сейчас — заглушка).
-- ============================================================================

NSQC4.RegisterModule("quests", function()

    local P = NSQC4.QuestsDfProfessionsApi
    if not P then
        print("|cffff0000[NSQC4]|r Swimmer: Professions/Init.lua не загружен.")
        return
    end

    -- ========================================================================
    -- Формула кликов Пловца.
    --   Вода не добывается работой, поэтому кликов всегда 1 (заглушка).
    --   Сигнатура совпадает с другими профессиями:
    --     clicks(hardness, prof_pct, stat_pct) -> int >= 1
    --   Это позволяет Work:Tick и Resolve работать единообразно,
    --   если в будущем появится «работа на воде».
    -- ========================================================================
    local function clicks(hardness, prof_pct, stat_pct)
        return 1
    end

    -- ========================================================================
    -- Регистрация профессии.
    -- ========================================================================
    P:Register("swimmer", {
        name    = "Пловец",
        desc    = "Умеет плавать и пересекать воду.",
        terrain = "water",          -- к какому объекту применяется
        stat    = "agility",        -- какой параметр ускоряет (ловкость)
        clicks  = clicks,           -- формула кликов (заглушка: всегда 1)
        work    = { verb = "плывёт", duration = 1, yields = nil },
    })

end)