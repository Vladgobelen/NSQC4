-- ============================================================================
-- NSQC4 / Quests / df / Dwarf / Gods
-- Три бога-основателя дворфов и kinship (сумма битов).
--   1 — Железобетонсон, 2 — Шельма Задранец, 4 — Джиамо Казанунда
-- ============================================================================

NSQC4.RegisterModule("quests", function()

    local Gods = {}
    NSQC4.QuestsDfDwarfGods = Gods

    Gods.BITS = {
        [1] = "Железобетонсон",
        [2] = "Шельма Задранец",
        [4] = "Джиамо Казанунда",
    }

    Gods.MAX_BIT = 4

    local KINSHIP = {
        -- Боги
        ["Железобетонсон"]   = 1,
        ["Шельма Задранец"]  = 2,
        ["Джиамо Казанунда"] = 4,

        -- [3]
        ["Бон"] = 1, ["Кон"] = 2, ["Цон"] = 1, ["Шон"] = 2, ["Свн"] = 1,
        ["Пон"] = 1, ["Щон"] = 2, ["Гон"] = 1, ["Рон"] = 2, ["Мон"] = 1,

        -- [4]
        ["Свая"] = 1, ["Шлак"] = 1, ["Песок"] = 1,

        -- [5]
        ["Бетон"] = 1, ["Кирпич"] = 5, ["Цемент"] = 1,
        ["Гравий"] = 1, ["Стяжка"] = 5, ["Щебень"] = 1,

        -- [6]
        ["Свайс"] = 1, ["Шлакс"] = 1, ["Песокс"] = 1, ["Щебенс"] = 1,
        ["Бетонс"] = 1, ["Кирпичс"] = 5, ["Цементс"] = 1,

        -- [7]
        ["Арматур"] = 1, ["Раствор"] = 1, ["Мастика"] = 5, ["Сайдинг"] = 5,
        ["Гравийс"] = 1, ["Растворс"] = 1, ["Свайсон"] = 1,
        ["Песоксон"] = 1, ["Щебенсон"] = 1, ["Мастикс"] = 3,

        -- [8]
        ["Опалубка"] = 5, ["Штукатур"] = 5, ["Бетонсон"] = 1,
        ["Кирпичсон"] = 5, ["Цементсон"] = 1, ["Шлаксон"] = 1,
        ["Гравийсон"] = 1, ["Мастиксон"] = 5, ["Задранец"] = 6,

        -- [9]
        ["Фундамент"] = 1, ["Гидроизол"] = 1, ["Растворсон"] = 1,

        -- [10]
        ["Утеплитель"] = 4,

        -- [11]
        ["Гипсокартон"] = 5, ["Железобетонс"] = 1,
    }

    Gods.KINSHIP = KINSHIP

    function Gods:GetKinship(name)
        if type(name) ~= "string" or name == "" then return 0 end
        return KINSHIP[name] or 0
    end

    -- b, а не bit — чтобы не перекрывать глобальную таблицу bit в шаге цикла
    function Gods:GetGods(kinship)
        local list = {}
        kinship = tonumber(kinship) or 0
        local b = 1
        while b <= Gods.MAX_BIT do
            if math.floor(kinship / b) % 2 == 1 then
                local name = Gods.BITS[b]
                if name then list[#list + 1] = name end
            end
            b = b * 2
        end
        return list
    end

    function Gods:GetByName(name)
        local k = self:GetKinship(name)
        return k, self:GetGods(k)
    end

end)