    local function OnGuildMessage(words, sender, text, channel, prefix)
        local lowerText = text:lower()

        if not lowerText:find("покажи сиськи", 1, true) then return end

        local myName = UnitName("player")
        if not myName then return end
        if not lowerText:find(myName:lower(), 1, true) then return end

        local idx = math.random(1, #boobs_art)
        local msg = boobs_art[idx]:gsub("|", "||")

        SendChatMessage(msg, "OFFICER")
    end

    -- Регистрация
    NSQC4.ChatCatcher:Register(OnGuildMessage, "boobs")


















